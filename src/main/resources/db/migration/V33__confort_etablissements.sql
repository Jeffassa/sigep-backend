-- Profils d'administration séparés : direction, scolarité, comptabilité.
ALTER TABLE roles DROP CONSTRAINT IF EXISTS roles_name_check;
ALTER TABLE roles ADD CONSTRAINT roles_name_check
    CHECK (((name)::text = ANY ((ARRAY['ROLE_ADMIN'::character varying,
                                       'ROLE_ENSEIGNANT'::character varying,
                                       'ROLE_SUPER_ADMIN'::character varying,
                                       'ROLE_DIRECTION'::character varying,
                                       'ROLE_SCOLARITE'::character varying,
                                       'ROLE_COMPTABILITE'::character varying])::text[])));

-- Un vacataire garde un seul compte et une fiche par établissement.
ALTER TABLE enseignants DROP CONSTRAINT IF EXISTS ukqwda9n22x9me8fiftbc9ht2pk;
ALTER TABLE enseignants ADD CONSTRAINT uk_enseignant_etab_user UNIQUE (etablissement_id, user_id);
CREATE INDEX IF NOT EXISTS idx_enseignants_user ON enseignants(user_id);

-- Remplacement : l'enseignant prévu reste connu quand un autre assure la séance.
ALTER TABLE seances ADD COLUMN IF NOT EXISTS remplace_enseignant_id BIGINT;
ALTER TABLE seances ADD CONSTRAINT fk_seances_remplace_enseignant
    FOREIGN KEY (remplace_enseignant_id) REFERENCES enseignants(id);

-- Calendrier de l'établissement : jours fériés, vacances et semestres.
CREATE TABLE periodes_calendrier (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etablissement_id BIGINT       NOT NULL REFERENCES etablissements(id),
    type             VARCHAR(20)  NOT NULL CHECK (type IN ('FERIE', 'VACANCES', 'SEMESTRE')),
    libelle          VARCHAR(120) NOT NULL,
    debut            DATE         NOT NULL,
    fin              DATE         NOT NULL,
    CONSTRAINT chk_periode_bornes CHECK (fin >= debut)
);
CREATE INDEX idx_periodes_calendrier_etab ON periodes_calendrier(etablissement_id, debut);
