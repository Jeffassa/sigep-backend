-- Annonces de la plateforme : un bandeau publié par le super administrateur dans les consoles
-- de tous les établissements (maintenance, nouveauté, information). Donnée de la plateforme,
-- sans établissement : elle s'adresse à tous.
CREATE TABLE annonces (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type     VARCHAR(20)  NOT NULL CHECK (type IN ('INFORMATION', 'NOUVEAUTE', 'MAINTENANCE')),
    message  VARCHAR(300) NOT NULL,
    debut    TIMESTAMP    NOT NULL,
    fin      TIMESTAMP,
    auteur   VARCHAR(255) NOT NULL,
    creee_le TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_annonce_bornes CHECK (fin IS NULL OR fin >= debut)
);
CREATE INDEX idx_annonces_fin ON annonces(fin);
